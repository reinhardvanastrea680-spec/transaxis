"use server";

import { createClient } from "@supabase/supabase-js";
import { createClient as createServerClient } from "@/lib/supabase/server";

function getServiceClient() {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL!;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY!;
  return createClient(url, key, {
    auth: { autoRefreshToken: false, persistSession: false },
  });
}

export async function createOrganization(name: string) {
  const supabase = await createServerClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    return { error: "Not authenticated" };
  }

  const service = getServiceClient();

  // Check if already has org
  const { data: profile } = await service
    .from("profiles")
    .select("org_id")
    .eq("id", user.id)
    .maybeSingle();

  if (profile?.org_id) {
    return { success: true };
  }

  // Create organization (join_code is generated by the DB default)
  const { data: org, error: orgError } = await service
    .from("organizations")
    .insert({ name: name.trim() })
    .select("id, join_code")
    .single();

  if (orgError || !org) {
    return { error: orgError?.message ?? "Failed to create organization" };
  }

  // Upsert profile with org link (handles case where trigger didn't create profile)
  const { error: profileError } = await service
    .from("profiles")
    .upsert(
      { id: user.id, org_id: org.id, role: "owner", full_name: user.email },
      { onConflict: "id" }
    );

  if (profileError) {
    return { error: profileError.message };
  }

  return { success: true };
}

export async function joinOrganization(joinCode: string) {
  const supabase = await createServerClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) return { error: "Not authenticated" };

  const code = joinCode.trim().toUpperCase();
  if (!code) return { error: "Enter a join code" };

  const service = getServiceClient();

  // Look up the org by join code using the service role (server-side only,
  // so the anon key can never enumerate organizations).
  const { data: org, error: lookupError } = await service
    .from("organizations")
    .select("id, name")
    .eq("join_code", code)
    .maybeSingle();

  if (lookupError) return { error: lookupError.message };
  if (!org) return { error: "Invalid join code. Check with your organization owner." };

  const { data: profile } = await service
    .from("profiles")
    .select("org_id")
    .eq("id", user.id)
    .maybeSingle();

  if (profile?.org_id === org.id) {
    return { success: true, orgName: org.name };
  }

  if (profile?.org_id) {
    return { error: "You already belong to another organization." };
  }

  const { error: updateError } = await service
    .from("profiles")
    .update({ org_id: org.id, role: "staff" })
    .eq("id", user.id);

  if (updateError) return { error: updateError.message };

  await service.from("audit_logs").insert({
    org_id: org.id,
    actor_id: user.id,
    action: "staff.joined_with_code",
    entity_type: "organization",
    entity_id: org.id,
    metadata: { join_code: code },
  });

  return { success: true, orgName: org.name };
}
